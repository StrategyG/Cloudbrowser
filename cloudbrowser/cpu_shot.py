"""Bounded, reproducible CPU-only 2D shot rendering from registered PNG artifacts.

This is sprite-pose compositing, not 3D reconstruction, IK, or generative video.
No shell, network media inputs, user-provided filter text, or GPU required.
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

from PIL import Image, UnidentifiedImageError

from .media import Media


def _digest(path: Path) -> str:
    sha = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            sha.update(block)
    return sha.hexdigest()


def _png(media: Media, artifact_id: str, *, actor: bool = False) -> Path:
    path = media.artifacts.path(artifact_id)
    if path.suffix.lower() != ".png":
        raise ValueError("CPU shot only accepts registered PNG artifacts.")
    try:
        with Image.open(path) as image:
            if image.format != "PNG" or image.width * image.height > 16_000_000:
                raise ValueError("Invalid or oversized PNG input.")
            if actor and not (image.mode in {"RGBA", "LA"} or "transparency" in image.info):
                raise ValueError("Actor poses must contain an alpha channel.")
            image.verify()
    except (UnidentifiedImageError, OSError, SyntaxError) as exc:
        raise ValueError("Invalid PNG input.") from exc
    return path


async def render_cpu_shot(
    media: Media, *, background_id: str, pose_ids: list[str],
    duration: float = 5, actor_width: int = 160, start_x: int = 100,
    end_x: int = 100, y: int = 250, pose_hold_frames: int = 3,
    width: int = 1280, height: int = 720, fps: int = 24,
) -> dict:
    """Render one independently reusable MP4 shot; cache by input content hash.

    Multiple transparent pose PNGs cycle at a bounded rate while the sprite
    translates linearly between start_x and end_x. Pose order is authored.
    """
    Media._dimensions(width, height, fps)
    if not (isinstance(duration, (int, float)) and math.isfinite(duration)
            and 1 <= duration <= 15):
        raise ValueError("CPU shot duration must be 1–15 seconds.")
    if not 1 <= len(pose_ids) <= 8:
        raise ValueError("Supply 1–8 registered PNG pose artifacts.")
    if not 32 <= actor_width <= min(width, 800) or not 1 <= pose_hold_frames <= 12:
        raise ValueError("Invalid actor width or pose hold frames.")
    if not (all(isinstance(v, int) for v in (start_x, end_x, y))
            and -actor_width <= start_x <= width
            and -actor_width <= end_x <= width
            and -height <= y <= height):
        raise ValueError("Actor positions outside supported canvas bounds.")

    total_frames = round(duration * fps)
    if not 1 <= total_frames <= 900:
        raise ValueError("Shot frame budget exceeded.")
    sources = [_png(media, background_id)]
    sources.extend(_png(media, pose_id, actor=True) for pose_id in pose_ids)
    payload = {
        "engine": "cpu-shot-v1", "inputs": [_digest(path) for path in sources],
        "frames": total_frames, "actor_width": actor_width, "start_x": start_x,
        "end_x": end_x, "y": y, "pose_hold_frames": pose_hold_frames,
        "width": width, "height": height, "fps": fps,
    }
    key = "cpu-shot:" + hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    saved = media.artifacts.store.get(key)
    if saved:
        try:
            cached = json.loads(saved)
            path = media.artifacts.path(cached["id"])
            if _digest(path) == cached["sha256"]:
                return {"artifact": media.artifacts.store.artifact(cached["id"]),
                        "cache_hit": True, "fps": fps,
                        "duration_seconds": total_frames / fps,
                        "note": "Cached CPU sprite animation, not generated 3D."}
        except (ValueError, OSError, KeyError, TypeError, json.JSONDecodeError):
            pass

    args = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
            "-filter_complex_threads", "1"]
    for path in sources:
        args += ["-loop", "1", "-framerate", str(fps),
                 *media._input(path)]
    chain = [f"[0:v]scale={width}:{height}:force_original_aspect_ratio=decrease,"
             f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,setsar=1,format=rgba[bg]"]
    for index in range(len(pose_ids)):
        chain.append(f"[{index + 1}:v]scale={actor_width}:-2,format=rgba[p{index}]")
    previous = "bg"
    period = len(pose_ids) * pose_hold_frames
    denominator = max(1, total_frames - 1)
    # All filter parameters are bounded numeric values generated by this module.
    motion = f"{start_x}+({end_x}-{start_x})*min(n/{denominator},1)"
    for index in range(len(pose_ids)):
        high = (index + 1) * pose_hold_frames - 1
        low = index * pose_hold_frames
        target = f"o{index}"
        enabled = f"between(mod(n\\,{period})\\,{low}\\,{high})"
        chain.append(f"[{previous}][p{index}]overlay=x='{motion}':y={y}:"
                     f"enable='{enabled}':eval=frame:format=auto[{target}]")
        previous = target
    chain.append(f"[{previous}]format=yuv420p[out]")
    artifact_id, output, filename = media.artifacts.allocate("cpu_sprite_shot.mp4")
    args += ["-filter_complex", ";".join(chain), "-map", "[out]",
             "-frames:v", str(total_frames), "-r", str(fps),
             "-c:v", "libx264", "-preset", "veryfast", "-crf", "24",
             "-threads", "2", "-movflags", "+faststart", str(output)]
    try:
        await media._run(*args, timeout=300)
        info = await media.probe(output)
        videos = [s for s in info.get("streams", []) if s.get("codec_type") == "video"]
        if len(videos) != 1 or (videos[0].get("width"), videos[0].get("height")) != (width, height):
            raise ValueError("Rendered shot failed video dimension QC.")
        if videos[0].get("r_frame_rate") != f"{fps}/1":
            raise ValueError("Rendered shot failed FPS QC.")
        if abs(float(info.get("format", {}).get("duration", 0)) - total_frames / fps) > 0.1:
            raise ValueError("Rendered shot failed duration QC.")
        artifact = media.artifacts.register(artifact_id, output, filename)
        media.artifacts.store.set(key, json.dumps({"id": artifact_id, "sha256": _digest(output)}))
        return {"artifact": artifact, "cache_hit": False, "fps": fps,
                "duration_seconds": total_frames / fps,
                "note": "CPU-only sprite/pose animation. Motion quality requires visual review."}
    except BaseException:
        output.unlink(missing_ok=True)
        raise
